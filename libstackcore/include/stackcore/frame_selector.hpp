#pragma once

#include <cstddef>
#include <vector>

namespace stackcore {

// 参照との類似度の分布から、構造的な外れ値を切るしきい値を求める。
//
// なぜ絶対しきい値では足りないか:
// テアリング（横方向に引き裂かれた壊れフレーム）は「参照とまるで違う」わけではない。
// 実データ（木星SER 4617フレーム）での実測は ZNCC 0.72〜0.985 であり、
// 正常フレームの 0.993〜1.000 との差はわずかである。安全側に置いた
// 絶対しきい値（0.5など）は素通りしてしまう。
// 一方、正常フレームの類似度は極めて狭い範囲に固まるため、
// 分布からの外れ具合で見れば明確に分離できる。
//
// なぜこれが要るのか:
// 品質指標（勾配エネルギー）は「シャープさ」と「引き裂かれた段差」を区別できず、
// 壊れたフレームほど高いスコアを付ける。実データでは品質上位20フレームが
// すべて構造的な異常フレームだった。この網がないと、品質順の選択は
// 壊れたフレームから順に採ってしまう。
//
// 散らばりの尺度に中央絶対偏差(MAD)を使うのは、外れ値自身に引きずられないため。
// k は中央値から何σ（MADを正規分布換算したもの）離れたら外れ値とみなすか。
//
// floor_margin は、類似度がほぼ完全に揃っている動画（MADがほぼ0）で
// しきい値が中央値に貼り付き、正常フレームまで切ってしまうのを防ぐ下限。
//
// 要素数が min_samples 未満のときは判定を行わず、
// どのフレームも切らない値（-1）を返す。
double similarity_outlier_threshold(const std::vector<double>& similarities, double k,
                                    double floor_margin = 0.002,
                                    std::size_t min_samples = 8);

}  // namespace stackcore
